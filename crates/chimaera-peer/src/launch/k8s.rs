//! `chimaera k8s render`: the manifests for a fixed-size cluster on
//! Kubernetes. A StatefulSet whose pods run `peer start --provider k8s`, so
//! each finds the founders by their ordinal DNS names; no operator and no
//! custom resource.

/// What to render; every field is a `chimaera k8s render` flag.
#[derive(clap::Args, Clone, Debug)]
pub struct Spec {
    /// StatefulSet name; its pods are NAME-0, NAME-1, ...
    #[arg(long, default_value = "chimaera")]
    pub name: String,
    /// Namespace for every object (default: the one `kubectl apply` uses).
    #[arg(long)]
    pub namespace: Option<String>,
    /// Image with `chimaera` on PATH and the chimaera wheel installed
    /// (deploy/images/Dockerfile), running as uid 1000.
    #[arg(long)]
    pub image: String,
    #[arg(long, default_value_t = 3)]
    pub replicas: u32,
    /// Pods 0..FOUNDERS-1 found the cluster (default: min(3, replicas)).
    #[arg(long)]
    pub founders: Option<u32>,
    #[arg(long, default_value_t = 7700)]
    pub port: u16,
    /// Port of the client Service, for drivers outside the pods.
    #[arg(long, default_value_t = 7710)]
    pub client_port: u16,
    /// CPU per pod, request and limit (the peer offers its limit), e.g. 4 or 500m.
    #[arg(long)]
    pub cpus: Option<String>,
    /// Memory per pod, request and limit, e.g. 8Gi.
    #[arg(long)]
    pub memory: Option<String>,
    /// Size of each pod's data volume (Raft logs, code, results).
    #[arg(long, default_value = "10Gi")]
    pub storage: String,
    /// Secret holding the cluster token under the key `token` (default: NAME-token).
    #[arg(long)]
    pub token_secret: Option<String>,
    /// Also run the provisioner in the cluster, growing the pool from
    /// --replicas up to MAX peers under load (a Deployment whose Role may only
    /// read this StatefulSet and change its scale). Needs --namespace.
    #[arg(long, value_name = "MAX")]
    pub provisioner: Option<u32>,
}

/// A DNS-1123 label of at most `max` characters.
fn check_label(what: &str, s: &str, max: usize) -> Result<(), String> {
    let ok = !s.is_empty()
        && s.len() <= max
        && s.bytes().all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'-')
        && s.as_bytes()[0].is_ascii_lowercase()
        && !s.ends_with('-');
    if ok {
        Ok(())
    } else {
        Err(format!(
            "{what} {s:?} must be lowercase letters, digits and '-', start with a letter, and be at most {max} characters"
        ))
    }
}

/// A YAML scalar: JSON strings are valid YAML double-quoted strings.
fn q(s: &str) -> String {
    serde_json::to_string(s).expect("a string serializes")
}

/// The Services, StatefulSet and PodDisruptionBudget, as one YAML stream.
pub fn render(s: &Spec) -> Result<String, String> {
    // StatefulSet names leave room for the controller's revision-hash label.
    check_label("--name", &s.name, 52)?;
    if let Some(ns) = &s.namespace {
        check_label("--namespace", ns, 63)?;
    }
    let secret = s.token_secret.clone().unwrap_or_else(|| format!("{}-token", s.name));
    check_label("--token-secret", &secret, 253)?;
    if s.replicas == 0 {
        return Err("--replicas must be at least 1".into());
    }
    let founders = s.founders.unwrap_or(s.replicas.min(3));
    if founders == 0 || founders > s.replicas {
        return Err(format!("--founders must be between 1 and --replicas ({}), not {founders}", s.replicas));
    }
    if s.port == s.client_port {
        return Err("--port and --client-port must differ".into());
    }
    if let Some(max) = s.provisioner {
        if max < s.replicas {
            return Err(format!("--provisioner {max} is below --replicas {}", s.replicas));
        }
        if s.namespace.is_none() {
            return Err("--provisioner needs --namespace: its RoleBinding names the ServiceAccount's namespace".into());
        }
    }
    let (name, port, client_port, replicas) = (&s.name, s.port, s.client_port, s.replicas);
    let ns = s.namespace.as_ref().map(|n| format!("\n  namespace: {n}")).unwrap_or_default();
    let labels =
        |indent: &str| format!("{indent}app.kubernetes.io/name: chimaera\n{indent}app.kubernetes.io/instance: {name}");
    let amounts: Vec<String> = [("cpu", &s.cpus), ("memory", &s.memory)]
        .into_iter()
        .filter_map(|(k, v)| v.as_ref().map(|v| format!("{k}: {}", q(v))))
        .collect();
    let resources = if amounts.is_empty() {
        String::new()
    } else {
        let list = amounts.join(", ");
        format!("\n          resources:\n            requests: {{{list}}}\n            limits: {{{list}}}")
    };
    let (image, storage) = (q(&s.image), q(&s.storage));
    let mut out = format!(
        r#"# Generated by `chimaera k8s render`. Create the token Secret once, then apply:
#   kubectl create secret generic {secret} --from-literal=token="$(chimaera cluster token)"
#   chimaera k8s render ... | kubectl apply -f -
apiVersion: v1
kind: Service
metadata:
  name: {name}-peers{ns}
  labels:
{l4}
spec:
  # Peers find each other by pod DNS name; founders must resolve before they are ready.
  clusterIP: None
  publishNotReadyAddresses: true
  selector:
{l4}
  ports:
    - name: peer
      port: {port}
---
apiVersion: v1
kind: Service
metadata:
  name: {name}{ns}
  labels:
{l4}
spec:
  # Drivers outside the pods connect here with the cluster token.
  type: ClusterIP
  selector:
{l4}
  ports:
    - name: client
      port: {client_port}
      targetPort: client
---
apiVersion: apps/v1
kind: StatefulSet
metadata:
  name: {name}{ns}
  labels:
{l4}
spec:
  serviceName: {name}-peers
  replicas: {replicas}
  # OrderedReady would deadlock formation: pod 0 is not ready until the other founders exist.
  podManagementPolicy: Parallel
  # Peers of two peer levels refuse each other, so a release that raises the
  # level replaces every pod together (docs/deploy.md, "Upgrading").
  updateStrategy:
    type: OnDelete
  selector:
    matchLabels:
{l6}
  template:
    metadata:
      labels:
{l8}
      # Each peer serves its status as Prometheus metrics (CHIMAERA_METRICS_LISTEN).
      annotations:
        prometheus.io/scrape: "true"
        prometheus.io/port: "9700"
        prometheus.io/path: /metrics
    spec:
      automountServiceAccountToken: false
      # SIGTERM drains for CHIMAERA_DRAIN_SECONDS (default 30) before the peer exits.
      terminationGracePeriodSeconds: 45
      securityContext:
        runAsNonRoot: true
        runAsUser: 1000
        runAsGroup: 1000
        fsGroup: 1000
      containers:
        - name: peer
          image: {image}
          imagePullPolicy: IfNotPresent
          command: ["chimaera", "--dir", "/data", "peer", "start", "--provider", "k8s"]
          env:
            - name: CHIMAERA_K8S_SERVICE
              value: "{name}-peers"
            - name: POD_NAMESPACE
              valueFrom:
                fieldRef:
                  fieldPath: metadata.namespace
            - name: CHIMAERA_FOUNDERS
              value: "{founders}"
            - name: CHIMAERA_PORT
              value: "{port}"
            - name: CHIMAERA_CLIENT_PORT
              value: "{client_port}"
            - name: CHIMAERA_POOL
              value: "{name}"
            - name: CHIMAERA_METRICS_LISTEN
              value: "0.0.0.0:9700"
            - name: CHIMAERA_CLUSTER_TOKEN
              valueFrom:
                secretKeyRef:
                  name: {secret}
                  key: token
          ports:
            - name: peer
              containerPort: {port}
            - name: client
              containerPort: {client_port}
            - name: metrics
              containerPort: 9700
          # The client port opens once the cluster has formed.
          readinessProbe:
            tcpSocket:
              port: client
            periodSeconds: 2{resources}
          volumeMounts:
            - name: data
              mountPath: /data
            - name: shm
              mountPath: /dev/shm
      volumes:
        - name: shm
          emptyDir:
            medium: Memory
  volumeClaimTemplates:
    - metadata:
        name: data
      spec:
        accessModes: ["ReadWriteOnce"]
        resources:
          requests:
            storage: {storage}
---
apiVersion: policy/v1
kind: PodDisruptionBudget
metadata:
  name: {name}{ns}
  labels:
{l4}
spec:
  # Voluntary evictions never take a quorum.
  maxUnavailable: 1
  selector:
    matchLabels:
{l6}
"#,
        l4 = labels("    "),
        l6 = labels("      "),
        l8 = labels("        "),
    );
    if let (Some(max), Some(namespace)) = (s.provisioner, &s.namespace) {
        out += &provisioner(name, namespace, &image, &secret, client_port, replicas, max);
    }
    Ok(out)
}

/// The in-cluster provisioner: a ServiceAccount whose Role may only read this
/// StatefulSet and change its scale, and a one-replica Deployment running
/// `python -m chimaera.provisioner` as a remote driver of the cluster.
fn provisioner(name: &str, ns: &str, image: &str, secret: &str, client_port: u16, min: u32, max: u32) -> String {
    let who = format!("{name}-provisioner");
    let labels = |indent: &str| {
        format!("{indent}app.kubernetes.io/name: chimaera-provisioner\n{indent}app.kubernetes.io/instance: {name}")
    };
    format!(
        r#"---
apiVersion: v1
kind: ServiceAccount
metadata:
  name: {who}
  namespace: {ns}
---
apiVersion: rbac.authorization.k8s.io/v1
kind: Role
metadata:
  name: {who}
  namespace: {ns}
rules:
  # This StatefulSet and its size, nothing else.
  - apiGroups: ["apps"]
    resources: ["statefulsets", "statefulsets/scale"]
    resourceNames: ["{name}"]
    verbs: ["get", "patch"]
---
apiVersion: rbac.authorization.k8s.io/v1
kind: RoleBinding
metadata:
  name: {who}
  namespace: {ns}
roleRef:
  apiGroup: rbac.authorization.k8s.io
  kind: Role
  name: {who}
subjects:
  - kind: ServiceAccount
    name: {who}
    namespace: {ns}
---
apiVersion: apps/v1
kind: Deployment
metadata:
  name: {who}
  namespace: {ns}
spec:
  replicas: 1
  selector:
    matchLabels:
{l6}
  template:
    metadata:
      labels:
{l8}
    spec:
      serviceAccountName: {who}
      securityContext:
        runAsNonRoot: true
        runAsUser: 1000
      containers:
        - name: provisioner
          image: {image}
          imagePullPolicy: IfNotPresent
          command: ["python3", "-m", "chimaera.provisioner", "--k8s-statefulset", "{name}", "--namespace", "{ns}", "--min", "{min}", "--max", "{max}"]
          env:
            - name: CHIMAERA_ADDRESS
              value: "{name}:{client_port}"
            - name: CHIMAERA_TOKEN
              valueFrom:
                secretKeyRef:
                  name: {secret}
                  key: token
          resources:
            requests: {{cpu: "100m", memory: "256Mi"}}
            limits: {{memory: "512Mi"}}
"#,
        l6 = labels("      "),
        l8 = labels("        "),
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    fn spec() -> Spec {
        Spec {
            name: "chimaera".into(),
            namespace: None,
            image: "chimaera:dev".into(),
            replicas: 3,
            founders: None,
            port: 7700,
            client_port: 7710,
            cpus: None,
            memory: None,
            storage: "10Gi".into(),
            token_secret: None,
            provisioner: None,
        }
    }

    #[test]
    fn the_example_manifest_is_what_render_prints() {
        // deploy/k8s/example.yaml is `chimaera k8s render --image chimaera:dev`.
        assert_eq!(render(&spec()).unwrap(), include_str!("../../../../deploy/k8s/example.yaml"));
    }

    #[test]
    fn the_provisioner_gets_only_its_statefulsets_scale() {
        let mut s = spec();
        s.replicas = 2;
        s.provisioner = Some(8);
        assert!(render(&s).unwrap_err().contains("--namespace"), "a RoleBinding needs the namespace");
        s.namespace = Some("ml".into());
        let y = render(&s).unwrap();
        for want in [
            "kind: ServiceAccount\nmetadata:\n  name: chimaera-provisioner\n  namespace: ml",
            "resources: [\"statefulsets\", \"statefulsets/scale\"]\n    resourceNames: [\"chimaera\"]\n    verbs: [\"get\", \"patch\"]",
            "serviceAccountName: chimaera-provisioner",
            "\"--min\", \"2\", \"--max\", \"8\"",
            "value: \"chimaera:7710\"",
        ] {
            assert!(y.contains(want), "missing {want:?} in\n{y}");
        }
        assert_eq!(y.matches("automountServiceAccountToken: false").count(), 1, "peers still get no token");
        s.provisioner = Some(1);
        assert!(render(&s).unwrap_err().contains("below --replicas"));
    }

    #[test]
    fn render_sets_what_the_k8s_provider_and_formation_need() {
        let mut s = spec();
        s.name = "ml".into();
        s.namespace = Some("prod".into());
        s.replicas = 8;
        s.cpus = Some("4".into());
        s.memory = Some("16Gi".into());
        let y = render(&s).unwrap();
        for want in [
            "podManagementPolicy: Parallel",
            "updateStrategy:\n    type: OnDelete",
            "publishNotReadyAddresses: true",
            "automountServiceAccountToken: false",
            "terminationGracePeriodSeconds: 45",
            "medium: Memory",
            "maxUnavailable: 1",
            "serviceName: ml-peers",
            "value: \"ml-peers\"",
            "name: CHIMAERA_FOUNDERS\n              value: \"3\"",
            "name: ml-token",
            "namespace: prod",
            "requests: {cpu: \"4\", memory: \"16Gi\"}",
            "limits: {cpu: \"4\", memory: \"16Gi\"}",
            "command: [\"chimaera\", \"--dir\", \"/data\", \"peer\", \"start\", \"--provider\", \"k8s\"]",
            "name: CHIMAERA_METRICS_LISTEN\n              value: \"0.0.0.0:9700\"",
            "prometheus.io/port: \"9700\"",
        ] {
            assert!(y.contains(want), "missing {want:?} in\n{y}");
        }
        assert_eq!(y.matches("namespace: prod").count(), 4, "every object is namespaced");
        let pod_labels = "  template:\n    metadata:\n      labels:\n        app.kubernetes.io/name: chimaera\n        app.kubernetes.io/instance: ml\n";
        assert!(y.contains(pod_labels), "the pod template carries the selector's labels");
        assert_eq!(y.matches("\n---\n").count(), 3);
    }

    #[test]
    fn render_refuses_names_kubernetes_or_formation_would_reject() {
        let bad = [
            ("name", "Chimaera"),
            ("name", "-x"),
            ("name", "x\n  evil: 1"),
            ("namespace", "a_b"),
            ("replicas", "0"),
            ("founders", "4"),
            ("founders", "0"),
        ];
        for (field, value) in bad {
            let mut s = spec();
            match field {
                "name" => s.name = value.into(),
                "namespace" => s.namespace = Some(value.into()),
                "replicas" => s.replicas = value.parse().unwrap(),
                _ => s.founders = Some(value.parse().unwrap()),
            }
            assert!(render(&s).is_err(), "{field}={value:?} should be refused");
        }
        let mut s = spec();
        s.replicas = 1;
        assert!(render(&s).unwrap().contains("name: CHIMAERA_FOUNDERS\n              value: \"1\""));
        s.image = "reg.io/a\"b".into();
        assert!(render(&s).unwrap().contains(r#"image: "reg.io/a\"b""#), "the image is quoted");
    }
}
